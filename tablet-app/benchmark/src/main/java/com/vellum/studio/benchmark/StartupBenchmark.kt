package com.vellum.studio.benchmark

import androidx.benchmark.macro.BaselineProfileMode
import androidx.benchmark.macro.CompilationMode
import androidx.benchmark.macro.StartupMode
import androidx.benchmark.macro.StartupTimingMetric
import androidx.benchmark.macro.junit4.MacrobenchmarkRule
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.filters.LargeTest
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Cold app-startup timing for [TARGET_PACKAGE] (com.vellum.studio's MainActivity, launched via its
 * default LAUNCHER intent -- see [androidx.benchmark.macro.MacrobenchmarkScope.startActivityAndWait]).
 *
 * [StartupMode.COLD] kills the process before each iteration's launch, so every sample is a true
 * cold start (not a warm/hot re-launch of an already-resident process).
 *
 * Two [CompilationMode]s are measured side by side, now that this project has a real checked-in
 * Baseline Profile (app/src/main/baseline-prof.txt, generated by [BaselineProfileGenerator]):
 *
 * - [coldStartup] ([CompilationMode.DEFAULT]) reflects whatever ahead-of-time compilation state
 *   the device already has for this package -- the closest approximation to what a real user sees
 *   after installing normally, with no forced profile involvement either way.
 * - [coldStartupWithBaselineProfile] ([CompilationMode.Partial] with
 *   [BaselineProfileMode.Require]) forces the installed Baseline Profile to actually be used for
 *   partial ahead-of-time compilation before measuring, and -- because `Require` (rather than
 *   `UseIfAvailable`) throws instead of silently degrading if the profile or ProfileInstaller
 *   isn't actually present in the installed APK -- doubles as a hard runtime check that
 *   `app/src/main/baseline-prof.txt` is genuinely wired in, not just sitting in source unused.
 *
 * See tablet-app/benchmark-baseline.md for the actual measured numbers both of these produced (an
 * honest comparison, not an assumed win), and the exact device + date they came from.
 */
@LargeTest
@RunWith(AndroidJUnit4::class)
class StartupBenchmark {

    @get:Rule
    val benchmarkRule = MacrobenchmarkRule()

    @Test
    fun coldStartup() = benchmarkRule.measureRepeated(
        packageName = TARGET_PACKAGE,
        metrics = listOf(StartupTimingMetric()),
        compilationMode = CompilationMode.DEFAULT,
        startupMode = StartupMode.COLD,
        iterations = ITERATIONS,
    ) {
        pressHome()
        startActivityAndWait()
    }

    @Test
    fun coldStartupWithBaselineProfile() = benchmarkRule.measureRepeated(
        packageName = TARGET_PACKAGE,
        metrics = listOf(StartupTimingMetric()),
        compilationMode = CompilationMode.Partial(baselineProfileMode = BaselineProfileMode.Require),
        startupMode = StartupMode.COLD,
        iterations = ITERATIONS,
    ) {
        pressHome()
        startActivityAndWait()
    }

    companion object {
        private const val TARGET_PACKAGE = "com.vellum.studio"
        private const val ITERATIONS = 10
    }
}
